#       col = 2*f_col + 2*len + 1     （16 px 标签格 = 半个 32 px 数值格）
#   满宽时正好落在 v79 手写的 21 / 19 / 49 / 23 列，窄值才往左收。
#   下面这张表 + p1_unit_items() 让**静态版面（和预览图）**用同一个公式摆出默认值
#   的那一版；运行期 unit_lab 会把它覆盖成当前真实值的位置（两者同公式，不冲突）。
