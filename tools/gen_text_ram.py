def expand(cols, rows, items, code_w, charset=CHARS):
    """把 (格行, 格列, 文本) 列表展开成 cols x rows 的字符码网格。

    单独抽出来是为了让 tools/preview_pages.py 能走**同一条**展开路径渲染预览图 ——
    否则预览图和真正写进 ROM 的内容会各自漂移，预览就失去意义。

    charset：这一层认的字符表。lab 平面是 `CHARS`（含汉字），val 平面是
    `VAL_CHARS`（ASCII + ○）—— 两层各自一张表，才能把 ○ 只加进 val 而不动汉字码。
    """
    limit = 1 << code_w
    mem = [[0] * cols for _ in range(rows)]
    for (r, c, text) in items:
        for k, ch in enumerate(text):
            if ch not in charset:
                raise SystemExit("char '%s' (in %r) is not in the font charset" % (ch, text))
            code = charset.index(ch)
            if code >= limit:
                raise SystemExit("char '%s' (in %r) needs %d bits, but this plane is %d-bit"
                                 % (ch, text, code.bit_length(), code_w))
            rr, cc = r, c + k
            if rr >= rows or cc >= cols:
                raise SystemExit("text %r overflows the %dx%d plane at cell (%d,%d)"
                                 % (text, cols, rows, rr, cc))
            if mem[rr][cc] != 0:
                raise SystemExit("cell (%d,%d) written twice (text %r)" % (rr, cc, text))
            mem[rr][cc] = code
    return mem


def build(cols, rows, items, name, code_w, charset=CHARS):
    """把 (格行, 格列, 文本) 列表展开成一块 RAM 的 Verilog。

    code_w = 字符码位宽。lab 层要放汉字，所以是 ceil(log2(len(CHARS)))；
    val 层只用 ASCII + ○，保持 6 bit 不变 —— 那层是像素路径
    最吃紧的地方，没必要为不用的码位付代价。
    """
    mem = expand(cols, rows, items, code_w, charset)

    addr_w = max(1, (cols * rows - 1).bit_length())
    L = []
    L.append("//  %s: %d x %d cells (%d px pitch grid), %d-bit char code, 1 write + 1 read port"
             % (name, cols, rows, 16 if cols == LAB_COLS else 32, code_w))
    L.append("module %s (" % name)
    L.append("    input  wire              clk,")
    L.append("    input  wire              we,")
    L.append("    input  wire [%d:0]       waddr," % (addr_w - 1))
    L.append("    input  wire [%d:0]        wdata," % (code_w - 1))
    L.append("    input  wire [%d:0]       raddr," % (addr_w - 1))
    L.append("    output reg  [%d:0]        rdata" % (code_w - 1))
    L.append(");")
    L.append("    reg [%d:0] mem [0:%d];" % (code_w - 1, cols * rows - 1))
    L.append("    integer i;")
    L.append("    initial begin")
    L.append("        // 先把整块清零：空格也是一个合法字符码（码 0）。")
    L.append("        // 若不显式清，版面没写到的格在仿真里保持 X，那个 X 会顺着取字通路")
    L.append("        // （font_rom -> lab_sr -> glyph_bit -> with_txt）漏到背景像素上，")
    L.append("        // 让任何一句“这一片该是什么底色”的断言都读到 X。")
    L.append("        // 上板没有这个问题：综合出的 BRAM 未写过的字默认就是 0。")
    L.append("        for (i = 0; i < %d; i = i + 1) mem[i] = %d'd0;" % (cols * rows, code_w))
    L.append("        // 再铺版面")
    n = 0
    for r in range(rows):
        for c in range(cols):
            if mem[r][c] != 0:
                L.append("        mem[%d] = %d'd%d;  // (%d,%d) '%s'"
                         % (r * cols + c, code_w, mem[r][c], r, c, charset[mem[r][c]]))
                n += 1
    L.append("    end")
    L.append("    always @(posedge clk) begin")
    L.append("        if (we) mem[waddr] <= wdata;")
    L.append("        rdata <= mem[raddr];")
    L.append("    end")
    L.append("endmodule")
    L.append("")
    return "\n".join(L), n, addr_w


def all_texts():
    """所有会被写进文字平面的字符串。

    给 tools/make_cn_glyphs.py 用：它拿这份清单校验"版面里每个汉字都有字模"，
    省得屏上出现方框才发现漏字。
    """
    out = []
    for _tag, lab, val in PAGES:
        for _r, _c, t in lab + val:
            out.append(t)
    return out


def main():
    L = []
    L.append("//=============================================================================")
    L.append("// text_ram.v -- 自动生成，请勿手改")
    L.append("//   生成器: tools/gen_text_ram.py")
    L.append("//")
    L.append("//   每页两层文字 RAM：")
    L.append("//     <page>_lab_ram : %d x %d 格，格 16x16，配 font_rom_lab（10x14 ASCII 字形 / 16x16 汉字）"
             % (LAB_COLS, LAB_ROWS))
    L.append("//     <page>_val_ram : %d x %d 格，格 32x64，配 font_rom_val（30x42 字形）"
             % (VAL_COLS, VAL_ROWS))
    L.append("//")
    L.append("//   字符码 = %d（ASCII）+ %d（汉字）= %d 种（不含平面专属符号），顺序见 tools/cn_glyphs.py"
             % (ASCII_COUNT, len(CN_CHARS), ASCII_COUNT + len(CN_CHARS)))
    L.append("//     各平面另有只属于该层的符号：lab +%d（%s，码 %d..%d）⇒ %d 码；val +%d（%s，码 %d）⇒ %d 码"
             % (len(LAB_EXTRA), LAB_EXTRA, ASCII_COUNT + len(CN_CHARS), LAB_COUNT - 1, LAB_COUNT,
                len(VAL_EXTRA), VAL_EXTRA, ASCII_COUNT, VAL_COUNT))
    L.append("//     lab 层 %d bit（要放汉字），val 层 %d bit（%d 码）"
             % (LAB_CODE_W, VAL_CODE_W, VAL_COUNT))
    L.append("//")
    L.append("//   地址 = 格行 * 格列数 + 格列；读延迟 1 拍（输出已寄存）。")
    L.append("//   写口给运行期用：动态数值在消隐期覆写，静态版面由 initial 预置。")
    L.append("//=============================================================================")
    L.append("")
    L.append("`default_nettype none")
    L.append("")

    summary = []
    for (tag, lab, val) in PAGES:
        a, na, aw_a = build(LAB_COLS, LAB_ROWS, lab, "%s_lab_ram" % tag, LAB_CODE_W, LAB_CHARS)
        val_rows = VAL_ROWS_P1 if tag == "p1" else VAL_ROWS
        b, nb, aw_b = build(VAL_COLS, val_rows, val, "%s_val_ram" % tag, VAL_CODE_W, VAL_CHARS)
        L.append(a)
        L.append(b)
        summary.append((tag, aw_a, na, aw_b, nb))

    L.append("`default_nettype wire")

    txt = "\n".join(L) + "\n"
    assert not txt.startswith("﻿"), "BOM must not be emitted"
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(txt)

    print("wrote %s" % OUT)
    print("  charset: %d ascii + %d cjk + lab %s + val %s = lab %d codes / val %d codes "
          "(lab %d bit, val %d bit)"
          % (ASCII_COUNT, len(CN_CHARS), LAB_EXTRA, VAL_EXTRA, LAB_COUNT, VAL_COUNT,
             LAB_CODE_W, VAL_CODE_W))
    for (tag, aw_a, na, aw_b, nb) in summary:
        print("  %s_lab_ram : %d x %d cells, addr %d bit, %d non-empty"
              % (tag, LAB_COLS, LAB_ROWS, aw_a, na))
        print("  %s_val_ram : %d x %d cells, addr %d bit, %d non-empty"
              % (tag, VAL_COLS, VAL_ROWS_P1 if tag == "p1" else VAL_ROWS, aw_b, nb))


if __name__ == "__main__":
    main()
