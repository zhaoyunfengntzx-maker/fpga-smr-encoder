"""
gen_text_ram.py -- 从"字面的 ASCII 版面"生成两页文字平面 RAM

为什么版面写在 Python 里
------------------------
版面是文本，不是逻辑。写在生成器里，改版面就是改几个字符串，
不会把 RTL 搅乱；而且生成器能做 RTL 做不到的三件事：
  * 拒绝字库之外的字符（字库只有 48 个大写 ASCII + 89 个汉字，小写字母会被当场拦下）
  * 拒绝越界、拒绝同一格被写两次（复制粘贴漏改会立刻暴露）
  * 把"格行/格列"换算成地址，让人只看得到版面

两层网格（与 disp_engine.v 的读地址约定一一对应）
--------------------------------------------------
  lab 层：64 x 38 格，格 16x16 px，配 font_rom_lab（10x14 字形）
          地址 = 格行 * 64 + 格列，即 {lab_cy[5:0], lab_cx[5:0]}
  val 层：32 x 10 格，格 32x64 px，配 font_rom_val（30x42 字形）
          地址 = 格行 * 32 + 格列，即 {val_cy[3:0], val_cx[4:0]}

每页一个模块（p1_lab_ram / p6_lab_ram / ...），而不是把页号拼进地址：
页数少的时候这样**没有**填充浪费，而且读出来的选择就是一个 2 选 1。
页数多到 LUTRAM 放不下时，再改成单块 BRAM + 页号高位地址。

写口给运行期用：动态数值在消隐期覆写，静态版面由 initial 预置。
"""

