# ★ v82（任务B）：单位（kHz / RPM / DEG / REV）的落点 = f(该字段实际字符数)
# -----------------------------------------------------------------------------
#   v82 把数值字段改成左对齐（disp/val_format.v 的 S_WRW），四张卡的数值左边界
#   恒为 x 96 / 576；代价是数字右端随字符数变，单位若写死坐标就会飘：
#   "28.3"（4 字符）时 kHz 与数字之间会空出 110 多 px，"12345678"（8 字符）时又
