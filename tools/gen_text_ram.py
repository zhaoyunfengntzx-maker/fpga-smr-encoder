#   ★ v83：字段 5（A● B● Z○）从格行 10 下移到格行 11，格行 10 改成
#     "U● V● W○"（不再属于任何字段，由 disp/uv_state.v 每帧重写）。
_VAL_BY_FIELD = {(2, 3): 0, (2, 18): 1, (6, 3): 2, (6, 18): 3,
                 (10, 3): 4, (11, 18): 5}


def p1_unit_items():
    """按"贴着数值右端"的公式算四个单位的静态落点，返回 (格行, 格列, 串)。

    公式与 disp/unit_lab.v 逐字一致（见上）；len 取静态 P1_VAL 字面量的字符数，
    于是预览图 = 上板首帧 = 默认值那一版画面。
    """
    text = {}
    for r, c, s in P1_VAL:
        # ★ v83：格行 10 的 "U● V● W○" 不属于任何数值字段（是 uv_state 的运行期
        #   行），查不到字段号就跳过，别让它把 p1_unit_items 弄崩。
        k = _VAL_BY_FIELD.get((r, c))
        if k is not None:
            text[k] = s
    out = []
    for row, fld, f_col, unit in P1_UNITS:
        out.append((row, 2 * f_col + 2 * len(text[fld]) + 1, unit))
    return out


