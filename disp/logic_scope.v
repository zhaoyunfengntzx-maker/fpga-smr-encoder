// =============================================================================
// disp/logic_scope.v —— P4 ABZ/UVW 时序页的"按电角度装箱"存储
// =============================================================================
// 为什么不是时间轴上的一串采样点（spec §7.1 有明文）：
//
//   A/B 的电角度边沿率是 4 x inter x f_in。inter = 256、f_in = 1500 Hz 时是
//   1.536 MHz 的边沿率，而屏幕每帧只扫 58.6 帧 —— 把 A/B 直接画在时间轴上
//   得到的是**混叠**出来的假波形（看起来像低频摆动，实际是采样拍频）。
//
//   spec §7.1 给的做法是"按电角度 64/128 箱等效采样，并在图上注明"，
//   spec §3.2 也早就为它预算了"逐列 6-bit 状态（数字时序）"这一项。
//   本模块就是那个存储：128 箱，每箱 6 bit（{w,v,u,z,b,a}）。
//
// 为什么不需要双缓冲（与 P2/P3 不同）：
//
//   写入地址是**当前电角度所在的箱**，不是"第几个采样点"。所以第 b 箱只在
//   电角度落进 b 的时候被写 —— 一次电气周期写一遍，其余时间它一直保持上次
//   的值。这本身就是等效时间采样：每个箱存的永远是"该角度上的状态"。
//   一个电角度周期约 130 拍（50 MHz / 384 kHz），一帧有约 19,500 个电气周期，
//   所以每个箱在一帧里被重写约 19,500 次、且写进去的是同一个值（信号锁定）。
//   换句话说：P2/P3 需要双缓冲是因为"写者和读者访问的地址逐行交叉"，
//   而这里读者看到的每个箱的内容在一帧之内是稳定的，交叉不会产生撕裂。
//
// 写口为什么不加使能：
//
//   加一个"每个箱只写一次"的门（例如 angle[8:0] == 0）看起来更省，但
//   50 MHz / 384 kHz 时电角度每拍前进约 503 个计数，正好卡在 512 的箱宽上 ——
//   一旦信号稍快就会跳过整箱，跳过的箱就一直保持上电初值。无使能的写法
//   （每拍都写当前箱）不会漏任何一个箱，代价只是每拍翻转 6 bit 的 LUTRAM。
//
// 读口为什么有两个：
//
//   画方波除了"这一列是高还是低"还要画**竖直边沿**：箱子边界处电平翻转时，
//   要在箱首把高、低两条轨之间填满。这需要"前一箱"的值，而
//   一个读口一拍只能给一个地址。两个寄存读口换来的是：像素通路里只有
//   移位和比较，没有第二次访存、没有循环（spec §7.2）。
//
// v18：箱宽从 4 px 摊到 6.6875 px（P4 加宽到 spec §4.5 的 944×340）
//
//   轨迹区从 512 px 加宽到 856 px（x = 168..1023），**箱数仍然是 128**：
//   写口一个 clk 只能写一箱，而电角度每拍前进约 503 个计数（一个电气周期
//   只够写 ~130 箱），128 箱已经是这条采集通路的分辨率上限 —— 再加宽屏幕
//   只能把箱"摊开"，不能凭空多出箱来。于是读地址从 `dx >> 2` 换成
//   `(dx * 153) >> 10`（153/1024 = 0.14941，精确值 128/856 = 0.14953）：
//     * 153 = 128 + 16 + 8 + 1，只用移位与加法，不占 DSP、组合深度 2 级；
//     * 最大偏差 0.8 px（箱边界处），肉眼不可见；
//     * 128 箱**每一箱都仍然可达**（不像 2 倍拉伸那样每两箱跳掉一箱）。
//   "上一箱"的地址用同一个式子算 dx-1（dx==0 时回绕到 855 ⇒ 第 127 箱），
//   于是画边沿的判据从"箱首那一个像素"（旧 `dx[1:0]==0`）简化成
//   "这一像素的箱电平与上一像素的箱电平不同"，与箱宽无关。
// =============================================================================

`default_nettype none

module logic_scope (
    input  wire        clk,
    input  wire        rst_n,

    // ---- 采样侧：每拍把当前电角度所在的箱写成当前 6 位状态 ----
    input  wire [15:0] angle,     // 电角度 0..65535 = 0..360°
    input  wire [5:0]  io6,       // {w,v,u,z,b,a}，即 q_io_state[5:0]

    // ---- 显示侧：轨迹区像素偏移 dx（0..855 = 856 px，见文件头 v18）----
    input  wire [9:0]  dx,

    output reg  [5:0]  q,         // dx 所在箱的状态
    output reg  [5:0]  qp         // dx-1 所在箱的状态（画边沿用）
);

    // 128 箱 x 6 bit = 768 bit，LUTRAM 级别（spec §3.2 预算 0.17 tile）
    reg [5:0] mem [0:127];
    integer i;

    // 上电清零：综合出的 RAM 默认就是 0，这里显式写一遍是为了**仿真**——
    // 不写的话未访问过的箱在 xsim 里是 X，X 会顺着判色链污染整块底色断言。
    // （disp/text_ram.v 在 U-11 那轮踩过同一个坑：版面 RAM 只预置有字的格。）
    initial begin
        for (i = 0; i < 128; i = i + 1) mem[i] = 6'd0;
    end

    wire [6:0] wbin = angle[15:9];                       // 写箱 0..127

    // 读箱：856 px 摊到 128 箱（见文件头 v18）。越界（轨迹区之外）喂 0，
    // 免得在仿真里索引到 [0:127] 之外染出 X —— 那些像素本来就被 lg_tband 挡掉。
    wire        in_tx = (dx  < 10'd856);
    wire [9:0]  dxp   = (dx == 10'd0) ? 10'd855 : (dx - 10'd1);
    wire [17:0] mul_a = (dx  << 7) + (dx  << 4) + (dx  << 3) + dx;
    wire [17:0] mul_b = (dxp << 7) + (dxp << 4) + (dxp << 3) + dxp;
    wire [6:0]  rbin  = in_tx ? mul_a[17:10] : 7'd0;
    wire [6:0]  rbinp = (dxp < 10'd856) ? mul_b[17:10] : 7'd0;

    always @(posedge clk) begin
        mem[wbin] <= io6;                                // 无使能：见文件头
        q  <= mem[rbin];
        qp <= mem[rbinp];
    end

endmodule

`default_nettype wire
