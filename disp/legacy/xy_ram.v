//=============================================================================
// disp/xy_ram.v —— P3 李萨如 XY 页的点阵存储（1 bit/像素，双缓冲）
//-----------------------------------------------------------------------------
//   131072 x 1 bit = 128 Kbit（4 块 RAMB36）。
//   地址 17 位 = {缓冲区, by[7:0], bx[7:0]}：
//     最高位  = 双缓冲选择位（帧首互换）
//     中间 8 位 = 位图行，低 8 位 = 位图列
//   位图本体只用到 192 x 192（bx, by < 192），剩下的地址不解码任何几何。
//   **这是故意的浪费**：多花半块 RAMB36，换"地址 = 三段纯拼接" —— 像素通路里
//   没有乘法、没有比较链，只有一次减法把屏幕坐标平移到位图坐标。spec 7.2 禁止
//   `char_code * 16 + y[3:0]` 这类组合乘法出现在像素路径上，这里是同一个约束。
//
//   为什么用点阵而不是 P2 那种"每列一个区间"：
//     P2 的横轴是时间，同一列只有一个样本区间，所以"每列存 [lo,hi]"够用。
//     XY 图上同一条曲线会**折回同一列多次**（圆/8 字），列区间表达不了它，
//     只能存二维点阵。代价是每像素 1 bit 而不是每列 32 bit。
//
//   为什么双缓冲：理由与 disp/wave_ram.v 完全相同（见该文件头注释）。差别只在
//   这里除了"画"还要"擦" —— 上一帧的点如果不擦掉，屏上是**会累积成一片**的，
//   所以写面在每帧开头先整面清零（65536 拍，一帧有 853440 拍，余量充足），
//   再往上打点。擦与画都在**写面**上做，显示面整帧不动。
//
//   `initial` 清零：xsim 里未初始化的 BRAM 读出来是 X，X 会顺着 `xy_d1` 污染
//   "这一像素该是什么颜色"的判定，让所有底色断言读到 X。清零后"还没画"在屏上
//   就是纯绘图底色，可见且诚实；综合出的 BRAM 初值也是这段 initial，所以这是
//   仿真与硬件的**行为对齐**，不是为了让测试通过而加的特例。
//=============================================================================
`default_nettype none

module xy_ram (
    input  wire        clk,
    input  wire        we,
    input  wire [16:0] waddr,
    input  wire        wdata,
    input  wire [16:0] raddr,
    output reg         rdata
);

    reg mem [0:131071];
    integer i;

    initial begin
        for (i = 0; i < 131072; i = i + 1)
            mem[i] = 1'b0;
    end

    always @(posedge clk) begin
        if (we)
            mem[waddr] <= wdata;
        rdata <= mem[raddr];
    end

endmodule

`default_nettype wire
