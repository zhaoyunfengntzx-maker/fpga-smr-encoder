    initial begin
        // 先把整块清零：空格也是一个合法字符码（码 0）。
        // 若不显式清，版面没写到的格在仿真里保持 X，那个 X 会顺着取字通路
        // （font_rom -> lab_sr -> glyph_bit -> with_txt）漏到背景像素上，
        // 让任何一句“这一片该是什么底色”的断言都读到 X。
        // 上板没有这个问题：综合出的 BRAM 未写过的字默认就是 0。
        for (i = 0; i < 320; i = i + 1) mem[i] = 6'd0;
        // 再铺版面
    end
    always @(posedge clk) begin
        if (we) mem[waddr] <= wdata;
        rdata <= mem[raddr];
    end
endmodule

