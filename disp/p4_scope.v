//=============================================================================
// disp/p4_scope.v —— P4「逻辑时序」双窗口**单次触发**采样器（v78 重写）
//-----------------------------------------------------------------------------
// 一屏分两段时基，两段同时采、同时冻结：
//
//   触发点 = **电角度过零**（angle 从 0xFFFF 附近跨到 0）
//      ★ 为什么不是 A 相上升沿：A 每个电周期有 inter（标称 32）个上升沿，而两次采集
//        之间隔着 500 ms（不是电周期的整数倍）⇒ "抓下一个 A 沿"会在 32 个不同电角度
//        上随机落点，下区 U/V/W 的相位逐帧左右乱跳（TB 实测两帧 z_pos 一个 59、
//        一个 171）。电角度过零是**唯一对上下两区都锁相**的点：下区从 0° 开始，
//        上区也从同一个 A 相位开始（A 是电角度的固定函数）⇒ 每帧画面完全一样。
//        任务口径里写的就是"A 相上升沿（或电角度过零）"。
//
//   上区（行 0/1 = A/B）：窗宽 = 4 个 A 周期（现场测 A 上升沿之间的 clk 数 ×4），256 点
//       采样间隔 = 窗口/256（分数累加器，见 §2）⇒ 每个 A 周期 64 点
//       856 px / 256 点 = 3.344 px/点，一个 A 周期 = 64 点 = 214 px
//       标称：A 周期 ≈ 61 clk、4×A ≈ 244 clk ⇒ 采样间隔 <1 clk
//       ★ 上限：采样率最多 1 点/clk，所以 4×A < 256 clk（A 边沿 >780 kHz）时窗口
//         被拉成 256 clk，屏上是 4.25 个 A 周期而不是 4 个 —— 刻度 0/1A/2A/3A/4A
//         仍然对得上，只是末端多 1/4 格。TB 实测 A 边沿 9 个（4.25 周期本该 8.5）。
//
//   下区（行 2..5 = Z/U/V/W）：窗宽 = 1 个电周期（过零之间的 clk 数），256 点
//       标称电周期 ≈1950 clk ⇒ 采样间隔 ≈7.6 clk、一屏 ≈39 µs
//       U/V/W 每 60° 换相 ⇒ 每段 256/6 ≈ 42.7 点 = 143 px，画成台阶（相邻点不同就
//       在该列画一根竖线 = 样本边界）
//
//   Z 是"每机械转 1 个"的窄脉冲（40 ms 一次，宽度只有几个 clk），而窗口只有 1 个
//   电周期（≈39 µs）——"窗内正好碰上 Z"的概率 ≈0.1%，光靠采样 Z 行会永远空。
//   所以 Z 走两条路，任一命中就在该列画一根整行高竖标（disp_engine 的 lg_zmark）：
//     (a) 窗内真碰上 Z：上升沿把标记钉在当时那个样本上（lo_mem 的 zmark 位 = bit4）；
//     (b) Z 的**电角度相位**：一直记着最近一次 Z 上升沿时的电角度 z_ang，屏上在
//         (z_ang - 触发角) 对应的样本列画一根。Z 与电角度锁相 ⇒ 该差值每帧相同 ⇒
//         竖标稳定在同一列（TB 实测两帧都是样本 65 / dx 211..220）。
//
// ★ 为什么必须"单次触发 + 冻结"（v78 根因，替代 v75/v77 的角度分箱）：
//   v75/v77 是"按角度永久覆盖写"：每拍无条件把当前电平写进当前角度箱。
//   边沿率 800 kHz 时角速度 ≈1310 LSB/clk，而 inter=32 时 up_prod = angle*inter
//   每拍前进 32*1310 ≈ 41900 = **10.2 个箱**（箱 = 1/16 个 A 周期 = 4096 计数）
//   ⇒ 一次经过只覆盖到 64 箱里的 6~7 箱，其余箱留着上一次经过（相位不同）的值，
//   缓冲里是**很多次经过的混合物**；叠加 q_angle/q_io_state 被 de 门控（消隐期冻结）
//   就出现"零星短横线"。冻结 + 单次采集把"什么时候写"和"写哪一格"彻底解耦：
//   一次窗口内写满 0..255 各一次，写完就不动，直到下一次触发整体换帧。
//
// ★ 换帧策略：冷却窗口 CD_MAX = 25e6 clk（@50 MHz = 500 ms）。冷却结束后的第一个
//   电角度过零开始一次新采集，所以屏幕最多 2 Hz 换帧，人眼看到的是静态波形。
//   一次采集最长 5.2 ms（上区）/ 41.9 ms（下区，电频率 24 Hz 的极端值），相对
//   500 ms 冷却仍可忽略；换帧瞬间只有 0.02% 的概率正好在扫描这一页 ⇒ 不做双缓冲
//   也不会看见撕裂。
//
// ★ 时基为什么用"现场测出来的周期"而不是常量：A 周期 = 电周期/inter，速度一变窗口
//   就跟着变；测周期只要两个计数器（A 上升沿 / 电角度过零之间的 clk 数），**一次
//   除法都不用**（点位由分数累加器平均出来）。这样"4 个 A 周期"与"1 个电周期"两个
//   口径在 3 kHz ~ 400 kHz(A 相) 范围内都成立。
//
// 存储：256×4 + 256×9 bit = 3328 bit，全部 distributed LUTRAM，**不占 BRAM**
//      （BRAM 已 48/50）。每个样本除了电平，还存"和上一个样本比有没有跳变"的边沿位
//      —— 见 §4 的说明（这样读口只需要一个地址）。
//
// ★ 三个 Vivado LUTRAM 推断陷阱（这一版踩全了，v78 之前 LUT 从 82% 冲到 91% 的根因）：
//   ① 读口不能对同一片 memory 用两个不同地址（sidx 与 sidx-1）：Vivado 只认
//      1 写 + 1 读的 simple dual port。⇒ 边沿位改在**写**的时候算好存进去。
//   ② 写语句不能放在带 `negedge rst_n` 的 always 块里，哪怕不在复位分支内：
//      日志原文 "RAM is sensitive to asynchronous reset signal, this RTL style is
//      not supported"。⇒ 写地址/写数据/写使能全做成组合线网，写操作单独一个
//      `always @(posedge clk)`（§4b）。
//   ③ 不能用常量下标写存储（`mem[8'd0] <= ...`）：会被当成访问某个具体寄存器。
//      ⇒ 触发拍的第 0 点也走同一个变址写口（wa_u 由 trig 选到 0）。
//
// 改版记录：
//   v75：按角度分箱（64 箱 / 128 箱），不占 BRAM；单窗口时域 856 µs 的替代。
//   v77：每箱只存电平，箱边界跳变在采样器内部算（qv/qlv），横线加粗 2 px。
//   v78：本版 —— 单次触发 + 冻结；触发 = 电角度过零；上区窗宽 4×A周期、下区窗宽
//        1×电周期，两区各 256 点、分数累加器定采样时刻；Z 用"边沿标记位 + 电角度
//        相位竖标"两条路；边沿位存进样本（单读口 LUTRAM）。
//   v79：**上板整页空白**的修复（v78 逻辑在仿真里逐点对，上板一个字都没有）。
//        定位结论：不是时钟域问题 —— disp/enc_top_disp.v:301 是
//        `assign lcd_pclk = sys_clk;`，像素域和系统域**同一个 50 MHz 时钟**，
//        综合日志也证明 up_mem/lo_mem 都被正确推断成 distributed RAM（RAM64M）。
//        真正的链条是：**trig 从来没成立过**。trig 是两片缓冲唯一的写使能
//        （we_u = trig | …, we_l = trig | …，busy 也只会被 trig 置位），
//        所以 trig 不成立 ⇒ 上电全 0 ⇒ 每一位都是 0 ⇒ 六条轨全在低轨、
//        边沿位全 0 ⇒ 屏上就是六条平线（和现象完全一致）。
//        让 trig 不成立的具体缺陷有两个，都在本版修掉：
//          ① e_wrap 只认正向过零 ⇒ 相位关系一反（AB 互换/Z 极性/反转）就永远
//             不触发：改成正/反向都认。
//          ② 角度不动（静止/没信号/环路 freeze）时 e_wrap 永远不来 ⇒ 加 200 ms
//             看门狗兜底触发，保证任何输入下都有画面。
//        另外补了"屏上自证"（dbg_* 抽头 + disp/p4_dbg_lab.v）和 Z 竖标的
//        z_seen 门控（没见过 Z 就不画假竖标）。
//=============================================================================
`default_nettype none

module p4_scope (
    input  wire        clk,
    input  wire        rst_n,
    input  wire [15:0] angle,        // 电角度 0..65535（连续抽头，**不**按 de 门控）
    input  wire [5:0]  io6,          // {w,v,u,z,b,a}（tap_io_state 低 6 位，连续）
    input  wire [4:0]  pairs,        // v84：rtl 的 cfg_pairs（0 视作 32，与 uvw_gen 一致）

    input  wire [9:0]  dx,           // 像素在轨迹区里的列号（0..855）

    // 上区：{b,a}
    output wire [1:0]  qu,           // 本列样本电平
    output wire [1:0]  qv,           // 本列是样本边界上的跳变（画竖线）
    // 下区：{w,v,u,z}
    output wire [3:0]  ql,
    output wire [3:0]  qlv,
    output wire        qz,           // 本列有 Z 上升沿标记（画竖标）
    output reg         armed,        // 已冻结一帧（上电后第一次采集完成）
    output reg  [15:0] frames,       // 累计采集（换帧）次数，诊断用

    // ---------------------------------------------------------------------
    // v79：**屏上自证**用的只读抽头（不占串口、不改 rtl/）
    //   为什么需要：上板整页空白时，六条轨全画在低轨只有两种可能 ——
    //   ① 从来没触发过（缓冲一个字节都没写过）；② 写进了但读出来全 0。
    //   这两件事在屏幕上看是同一个画面，而串口读寄存器要走 rtl/reg_file.v
    //   （本版不许改 rtl/）。所以把"卡在哪一环"打成几个数，交给
    //   disp/p4_dbg_lab.v 写到 P4 页右上角，拍一张照片就能定位。
    // ---------------------------------------------------------------------
    output wire [20:0] dbg_eclk,     // 实测电周期（clk 数）；0 = 一个过零都没数到
    output wire [7:0]  dbg_wp,       // 下区写指针：<2 = 没采过，255 = 采满
    output wire [1:0]  dbg_enok,     // 已数到的电角度过零个数（饱和 3，2 才算可信）
    output wire        dbg_cd,       // 500 ms 冷却已放行（1 = 随时可以触发）
    output wire        dbg_tmo,      // 最近一帧来自**兜底定时触发**（不是电角度过零）
    // ---- v84：窗口算法换掉之后的自证抽头 ----
    output wire [21:0] dbg_win,      // 本帧窗口（clk）= eclk*2048/pairs_eff，22 位饱和
    output wire        dbg_upok,     // U 边沿测到的电周期仍"看着正常"（交叉校验，不再参与定窗）
    output wire [2:0]  dbg_scnt,     // U 间隔 <4096 clk 的次数（饱和 7）：U 相抖动的自证
    output wire        dbg_nocap,    // 一个传感器过零都没数到 ⇒ 无信号（窗口已退回 1024）
    output wire [15:0] dbg_urise     // U 上升沿累计数（只给仿真/日志看，综合时会被裁掉）
);

    localparam integer NDEP = 256;   // 两个窗口各 256 点（8 位索引 ⇒ 正好 8 位宽）
    localparam [24:0]  CD_MAX = 25'd24_999_999;   // 500 ms @ 50 MHz

    // =========================================================================
    // 0. 抽头打一拍：把 disp_engine 的组合抽头（pos_rep 加了修正项，路径较长）
    //    隔到寄存器后面，采样/边沿/测周期都只用 a_q/i_q，路径与像素无关。
    //    ★ 这里**不能**用 de 门控（v77 的教训，见 disp_engine 第 2 节的注释）：
    //      消隐期冻结的样本会被时基当成新样本写进缓冲，一屏里就出现几百 clk
    //      的平线（上区一屏才 256 clk，等于整屏作废）。
    // =========================================================================
    reg [15:0] a_q, a_qq;
    reg [5:0]  i_q, i_qd;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            a_q <= 16'd0; a_qq <= 16'd0;
            i_q <= 6'd0;  i_qd <= 6'd0;
        end else begin
            a_q  <= angle;
            a_qq <= a_q;
            i_q  <= io6;
            i_qd <= i_q;
        end
    end

    wire a_rise = i_q[0] & ~i_qd[0];              // A 相上升沿
    wire z_rise = i_q[2] & ~i_qd[2];              // Z 脉冲上升沿
    // 电角度正向过零（跨 0/65536）。只比最高两位：一次真过零必然 11 -> 00，
    // 而 ANG_GLITCH_MAX(1024 LSB) 量级的小毛刺动不了 [15:14]，误触发的可能性
    // 比"整条 16 位比较 + 16 位延迟寄存器"省下来的 LUT 更划算。
    // ★ 极性：a_q 是**新**样本、a_qq 是旧样本，所以正向过零后看到的是
    //   a_q = 00 / a_qq = 11（写反了会一次也测不到电周期，下区窗口变 0）。
    //
    // ★★ v79 根因（上板整页空白的**第一**原因）：
    //   v78 只认"正向"过零（00 ← 11）。一旦编码器/正弦的相位关系反过来 ——
    //   AB 接线互换、Z 极性反了、motor 反转 —— 角度就是从 0 往 0xFFFF 回绕，
    //   判据变成 11 ← 00 永不成立 ⇒ e_wrap 恒 0 ⇒ trig 恒 0 ⇒ 两片缓冲
    //   一个字节都没写过（上电全 0）⇒ 六条轨全在低轨、边沿位全 0 ⇒
    //   整页只剩六条平线。仿真里永远走不到这条路：_p4_work/tb_p4_scope.v 的
    //   激励是 `ang <= ang + 16'd34` 的理想**正向**斜坡，只覆盖了一半相位关系。
    //   修法：正/反向都算一次过零（差 2 LUT）。反向时波形按时间反序显示，
    //   这对"反转"本身是正确的显示，不是错误。
    wire e_wrap_f = (a_q[15:14] == 2'b00) && (a_qq[15:14] == 2'b11);   // 正向跨 0
    wire e_wrap_r = (a_q[15:14] == 2'b11) && (a_qq[15:14] == 2'b00);   // 反向跨 0
    wire e_wrap   = e_wrap_f | e_wrap_r;

    // =========================================================================
    // 1. 现场测周期（两个计数器，无除法）
    //    ecnt/eclk：电角度过零之间的 clk 数（电周期）
    //    acnt/aclk：A 上升沿之间的 clk 数（A 周期）；饱和在 0xFFFF
    //    ★ acnt 饱和标志同时兼任"AB 关掉 / 没有 A 相"的判据（见 §2）。
    //    ★ 21 位够用：电周期最长 2^21 clk = 41.9 ms（电频率低于 24 Hz 才溢出），
    //      那时窗口长 41.9 ms、256 点、7.6 万 clk 一点，波形仍然可读。
    // =========================================================================
    reg [20:0] ecnt, eclk;
    reg [15:0] acnt, aclk;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            ecnt <= 21'd0; eclk <= 21'd0;
            acnt <= 16'd0; aclk <= 16'd0;
        end else begin
            if (e_wrap) begin ecnt <= 21'd0;            eclk <= ecnt; end
            else              ecnt <= ecnt + 21'd1;
            if (a_rise) begin acnt <= 16'd0;            aclk <= acnt; end
            else if (!(&acnt)) acnt <= acnt + 16'd1;    // 饱和：没有 A 相时不会回绕
        end
    end

    // =========================================================================
    // 1b. 下区时基：**量 U/V/W 自己的电周期**，不要用 eclk
    //   ★ v83 任务A 根因（上板自证数字反推，非猜测）：
    //     eclk 量的是**角度抽头 angle 的周期**，而 rtl/enc_top.v:1851 送来的 angle
    //     是 `angle = pos_ext[ZW-1:FRAC]`（rtl/enc_top.v:726）——**正弦/余弦传感器
    //     一个信号周期**的角度（CPR2048 ⇒ 每机械转 2048 个信号周期）。
    //     而 uvw_gen 吃的是 mech_angle（rtl/enc_top.v:833/1044，每转 2^16），
    //     eang = mech_angle * pairs ⇒ U/V/W 的电周期 = **一转 / pairs**，
    //     比 eclk 大 2048/pairs 倍（pairs=2 时大 1024 倍）。
    //     上板自证 ECLK=0x52F=1327 clk：2048 × 1327 = 2.72 M clk = 54.4 ms/转
    //     ⇒ 1103 rpm，与串口 1095 rpm 一致 ⇒ **eclk 是传感器信号周期，不是电周期**。
    //     旧 win_l = eclk 只截到 26.5 µs ≈ 电周期的 1/1024：
    //       · U/V/W 在窗口里一个跳变都没有 ⇒ 每行一根平线；
    //         换帧时相位漂移 ⇒ 平线在上下轨之间跳（用户看到的"总是变换上下"）；
    //       · Z 每转 1 个（54 ms），落进 26.5 µs 窗口的概率 ≈ 1/2048
    //         ⇒ 永远画不出 Z 的窄脉冲竖标。
    //   现在直接量 u 上升沿之间的 clk 数（= 一个电周期）当窗口：256 点正好铺满
    //   一个电周期，6 个 60° 扇区 = 6 根台阶，每扇区 856/6 ≈ 143 px。
    //   代价：22 位饱和计数器 + 22 位锁存；同时删掉 z_ang 的 16 位减法链（净 ~0 LUT）。
    // =========================================================================
    wire u_rise = i_q[3] & ~i_qd[3];        // u = io_state[3]（io6 = {w,v,u,z,b,a}）
    wire u_fall = ~i_q[3] & i_qd[3];        // u 的下降沿（触发点：电角度 180°）
    reg  [21:0] ucnt;                       // u 上升沿之后过了多少 clk（饱和：没 U 相也不回绕）
    reg  [21:0] uper;                       // 一个 U/V/W 电周期 = 多少个 clk
    reg  [1:0]  uen_ok;                     // 量到 ≥2 个 u 上升沿 ⇒ uper 可信
    // v84 诊断：uper 之所以会"看起来失效"，只可能是 u_rise 的间隔本身不对
    //   （U 相在扇区边界 ±hyst 上来回 ⇒ u_out 相邻拍抖动）。这里把
    //   "间隔短到不可能是电周期（<4096 clk）"的次数单独数出来，饱和 7，
    //   上板显示成 S=<up_ok><scnt[2:0]> 一个十六进制位：S=8 健康，S=F 就是抖动。
    reg  [2:0]  scnt;                       // u_rise 且 ucnt<4096 的次数（饱和）
    reg  [15:0] urise_cnt;                  // u_rise 总次数（饱和，只给仿真/日志）
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            ucnt   <= 22'd0;
            uper   <= 22'd0;
            uen_ok <= 2'd0;
            scnt   <= 3'd0;
            urise_cnt <= 16'd0;
        end else begin
            if (u_rise) begin
                ucnt <= 22'd0;
                uper <= ucnt;
                if (!(&uen_ok)) uen_ok <= uen_ok + 2'd1;
                if (!(&urise_cnt)) urise_cnt <= urise_cnt + 16'd1;
                // ★ v84b：必须用 uen_ok[0] 门一下 —— 上电后第一个 u_rise 的
                //   ucnt 是 0（计数器刚复位），不门的话 scnt 永远 ≥1，屏上
                //   S 就永远不是 8，"健康/抖动"这个判据自证不了自己。
                if (uen_ok[0] && (ucnt[21:12] == 10'd0) && !(&scnt))
                    scnt <= scnt + 3'd1;
            end else if (!(&ucnt)) begin
                ucnt <= ucnt + 22'd1;
            end
        end
    end
    wire up_ok = uen_ok[1];                 // 已量到 2 个 u 上升沿 ⇒ uper 可信

    // =========================================================================
    // 1c. v84：**确定性窗口**（不依赖 U 边沿）—— 主路径
    //   §1 已经自证：eclk 是**传感器信号周期**（每机械转 2048 个；上板 3127 clk
    //   @436 rpm ⇒ 一转化为 2048×eclk）。而 uvw_gen 吃 mech_angle，
    //   eang = mech_angle*pairs ⇒ 一个电周期 = 一转/pairs_eff。
    //     窗口 = eclk*2048/pairs_eff
    //   pairs_eff = cfg_pairs（0 视作 32，与 rtl/uvw_gen.v 同义）；除数用移位近似：
    //     pairs 1/2/4/8/16/32 精确（sh = 0/1/2/3/4/5，win = eclk<<(11-sh)），
    //     其它值按 ceil(log2) 取，误差 ≤2×，窗口里落 1~2 个电周期，肉眼无差别。
    //   ★ 为什么必须换掉 uper：U 相是 uvw_gen 的**寄存输出**，只在 in_valid 拍变，
    //     扇区边界 ±hyst 之间来回时会相邻拍抖动 ⇒ 量到的"电周期"只有几拍，
    //     win 退化成几百 clk，U/V/W 三条全平（v83 上板偶发画面的最可能来源）。
    //     uper 现在只做交叉校验（dbg_upok/dbg_scnt），**不参与定窗**。
    //   ★ 饱和：win 只有 22 位（acc_l 也是），eclk*2048/pairs 可达 2^32，
    //     所以先算 32 位再饱和到 22'h3F_FFFF，否则 acc_l 累加会回绕。
    // =========================================================================
    wire [4:0] pairs_eff = (pairs == 5'd0) ? 5'd32 : pairs;
    wire [2:0] pairs_sh  = (pairs_eff <= 5'd1)  ? 3'd0 :   // ceil(log2(pairs_eff))
                           (pairs_eff <= 5'd2)  ? 3'd1 :
                           (pairs_eff <= 5'd4)  ? 3'd2 :
                           (pairs_eff <= 5'd8)  ? 3'd3 :
                           (pairs_eff <= 5'd16) ? 3'd4 : 3'd5;
    wire [31:0] rev_clk  = {11'd0, eclk} << 11;   // eclk × 2048（纯接线）
    wire [31:0] win_raw  = rev_clk >> pairs_sh;   // 3 级 32 位移位器
    wire [21:0] win_det  = (|win_raw[31:22]) ? 22'h3F_FFFF : win_raw[21:0];
    wire        eclk_ok  = (eclk != 21'd0);       // 还没数到过一次过零 ⇒ 无信号

    //   （1c 的 Z 竖标寄存器 z_pos/z_ok 要引用 wp_l/busy_l，声明见 §3 之后）

    // =========================================================================
    // 2. 采样时刻：**分数累加器**（Bresenham 式），不是"每 N 个 clk 一点"
    //    为什么不用整数 dec：dec 只能是整数，A 周期 96 clk 时 dec 该是 1.5，
    //    取整成 2 会把"4 个 A 周期"拉成 5.33 个 —— 上区刻度写着 0/1A/2A/3A/4A，
    //    边沿会跑到刻度的 3/4 处，一眼就看出错。
    //    累加器做法：每个 clk 给 acc 加**窗口内的点数**（256），acc 越过窗口长度
    //    win 就采一点并减掉 win。稳态下采样间隔 = win/256，可以带小数
    //    （1.5 clk 一点靠 1,2,1,2… 平均出来），而窗口**严格**等于 win。
    //    代价：一个加法器 + 一个比较器（无除法器），精度 1 clk/点。
    //    上区 win = 4 × A 周期（两次 A 上升沿之间叫一个 A 周期），下区 win = 1 个电周期。
    //    ★ win 在触发拍**冻结**成 win_u/win_l：窗口中途变速不会改这一帧的时基。
    //    ★ 退化：win < 256（A 边沿 > 780 kHz，1 点/clk 都不够）时累加器恒溢出，
    //      变成"每 clk 一点"、窗口 256 clk —— 只是显示多于 4 个 A 周期，不会死锁。
    // =========================================================================
    // =========================================================================
    // 3. 触发与 500 ms 冷却
    //    触发 = **电角度过零**（angle 从 0xFFFF 附近跨到 0）。
    //    ★ 为什么不用 A 相上升沿：A 每个电周期有 inter（标称 32）个上升沿，而两次
    //      采集之间隔着 500 ms（不是电周期的整数倍）⇒ "抓下一个 A 沿"在 32 个不同
    //      电角度上随机落点，下区 U/V/W 的相位会逐帧左右乱跳（TB 里两帧 z_pos 一个
    //      59、一个 171 就是这个症状），上区虽然自锁 A 相位、下区却稳不住。
    //      电角度过零是唯一对**上下两区都锁相**的触发点：下区从 0° 开始，上区也从
    //      同一个 A 相位开始（A 是电角度的固定函数）⇒ 每帧画面完全一样。
    //      任务要求里写的就是"A 相上升沿（**或电角度过零**）为触发"。
    //    好处之三：不需要 a_absent 判断 —— AB 全关掉时角度照样在转，U/V/W/Z 照样
    //    有波形，页面不会停在"上电全 0"的画面上。
    // =========================================================================
    wire a_absent = &acnt;                        // 1.3 ms 内没有 A 上升沿（A 相缺席）

    //   ★ 上电第一帧不能用：复位后第一个过零的 ecnt 是"复位到该过零的 clk 数"，
    //     不是电周期。⇒ 数满 2 个过零（en_ok[1]）才允许触发，那时 eclk 已是真周期。
    //     代价 2 个触发器，延迟 2 个电周期（<80 µs，用户感觉不到）。
    reg [1:0] en_ok;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) en_ok <= 2'd0;
        else if (e_wrap && !(&en_ok)) en_ok <= en_ok + 2'd1;
    end
    wire ep_ok = en_ok[1];                        // 已量到 2 个过零 ⇒ eclk 可信

    reg [24:0] cd;
    reg        cd_done;                           // 0 = 冷却中，1 = 可以开始下一次采集

    // ---------------------------------------------------------------------
    // 3b. v79 **兜底触发**（"即使触发不成立，也不能整页空白"）
    //   第二类空白原因：角度**根本不动**。loop_filter.v 的 pos_out 在
    //   freeze / 无有效样点时是"冻结"而不是"回绕"（rtl/loop_filter.v:62），
    //   传感器静止、环路没锁、或者只是没接信号 —— 这几种情况下 e_wrap
    //   一次都不会来，v78 就永远不采集，屏上永远是上电全 0。
    //   所以加一个 200 ms 的看门狗：**等不到过零就自己触发一次**。
    //   这一帧采到的是"当前电平的时间切片"（角度不动 ⇒ U/V/W 是一条直线），
    //   但它证明链路是通的，而且屏上 dbg_tmo 位会亮，一眼就能和"真触发"区分。
    //   代价：24 位计数器 + 24 位相等比较（约 8 LUT，触发器本来就要占）。
    //   ★ 位宽必须是 24：9_999_999 > 2^23，写成 22 位会被截断成 1_611_391
    //     （= 32 ms），看起来"能用"但实际不是 200 ms（VRFC 10-8497 会报）。
    //   注意 200 ms > 最慢电周期 41.9 ms（24 Hz），所以正常旋转时它一次都不会动。
    // ---------------------------------------------------------------------
    localparam [23:0] TMO_MAX = 24'd9_999_999;    // 200 ms @ 50 MHz
    reg [23:0] tmo;
    wire tmo_hit = (tmo == TMO_MAX);
    //   ★ v83：触发源改成 **u 下降沿**（= 电角度 180°），下区从 180° 起拍。
    //     为什么不用 u 上升沿（0°）：rtl 的 Z 指数脉冲 z_idx_evt（rtl/enc_top.v:798
    //     `(ang_wrap_f|ang_wrap_b) && rev_cnt[POLE_BITS-1:0]==0`）正好落在电角度 0°
    //     上 —— 若从 0° 起拍，Z 就和触发点重合在**最左边第 0 格**，竖标看不见。
    //     从 180° 起拍，Z 落在窗口正中（第 128 个样本 ≈ dx 428），清晰可见；
    //     六个 60° 扇区边界只是整体平移半个周期，位置集合不变（仍是 143 px 一组）。
    //     旧 trig_e = e_wrap 是**传感器信号**过零（一个电周期里来 2048 次），锁不住相位。
    wire trig_e  = u_fall & up_ok & cd_done;      // 正常触发：U 相下降沿 = 电角度 180°
    wire trig_t  = tmo_hit & cd_done;             // 兜底触发：200 ms 没等到 u 下降沿
    wire trig    = trig_e | trig_t;
    reg  tmo_last;                                // 最近一帧是兜底触发（诊断用）

    //   ★ dbg_* 的 assign 放在文件末尾（§6）：wp_l/wp_u 是 §4 才声明的寄存器，
    //     在这里 assign 会报 VRFC 10-3380（used before its declaration）。

    // =========================================================================
    // 4. 采集状态机：两区各自"写满 256 点就停"，停住即冻结
    //    上区 4 个 A 周期、下区 1 个电周期后各自 busy 落 0（最长 5.2 ms / 41.9 ms，
    //    都远短于 500 ms 冷却，所以不会出现"采集没完就换帧"）；
    //    在 busy 为 0 期间这两片 LUTRAM **一个时钟都不写** ⇒ 画面冻结。
    // =========================================================================
    //   ★ 每片只有**一个**读地址（sidx）：Vivado 的 simple-dual-port 模板要求
    //     1 写 + 1 读，读两个不同地址会直接放弃 RAM 推断、退化成 256 个触发器
    //     + 256:1 读 mux（实测 LUT 从 82% 冲到 91%）。所以"样本边界跳变"在**写**
    //     的时候就算好存进 bit 里：写的时候上一个样本还在 upl/lol 里。
    (* ram_style = "distributed" *) reg [3:0] up_mem [0:NDEP-1];   // {eb,ea,b,a}
    (* ram_style = "distributed" *) reg [8:0] lo_mem [0:NDEP-1];   // {ew,ev,eu,ez,zmark,w,v,u,z}
    reg [1:0] upl;                    // 上一个写进 up_mem 的 {b,a}
    reg [3:0] lol;                    // 上一个写进 lo_mem 的 {w,v,u,z}

    reg        busy_u, busy_l;
    reg [7:0]  wp_u, wp_l;
    reg [18:0] acc_u;                 // 上区采样相位累加器
    reg [21:0] acc_l;                 // 下区采样相位累加器
    reg [17:0] win_u;                 // 上区窗口长度（clk）= 4 × A 周期
    reg [21:0] win_l;                 // 下区窗口长度（clk）= 1 × 电周期
    reg        z_sticky;

    //   累加器的下一个值（寄存器声明之后才能引用）
    wire [18:0] acc_u_n = acc_u + 19'd256;        // 19 位：win_u ≤ 4*65535，再加 255
    //   ★ v84：下区窗口可以顶到 22'h3F_FFFF，acc_l+256 会越过 2^22 ⇒ 比较器
    //     在回绕点会漏一拍采样、多等一整个窗口。多做一位（23 位）就彻底消掉。
    wire [22:0] acc_l_n = {1'b0, acc_l} + 23'd256;

    // =========================================================================
    // 1c. Z 竖标：窗口内采到 Z 时，直接记下**它是第几个样本**（wp_l 就是下区
    //     采样指针）。触发锁在 u 下降沿（电角度 180°）⇒ Z 的电相位逐帧固定
    //     ⇒ 竖标稳定落在同一列，不需要再拿角度做减法（旧 z_ang/ang_t 减法链已删）。
    reg [7:0]  z_pos;                 // Z 落在窗口里的样本号 0..255
    reg        z_ok;                  // 成功标过一次（没标过就不画"假竖线"）
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            z_pos <= 8'd0;
            z_ok  <= 1'b0;
        end else if (z_rise && busy_l) begin
            z_pos <= wp_l;
            z_ok  <= 1'b1;
        end
    end

    //   写口：**唯一一句写存储**（地址/数据都是线网）。
    //   ★ 千万不能写成 up_mem[8'd0] <= ...（常量下标）：Vivado 会认为那是在访问
    //     某个具体寄存器、不是 RAM 端口，于是放弃 LUTRAM 推断 —— 两片缓冲退化成
    //     1792 个触发器 + 256:1 读 mux，全设计 LUT 从 82% 直接冲到 91%
    //     （Synth 8-7186 "not inferred as ram due to incorrect usage"）。
    wire [7:0] wa_u = trig ? 8'd0 : wp_u;
    wire       we_u = trig | (busy_u & (acc_u_n >= {1'b0, win_u}));
    wire [3:0] wd_u = trig ? {2'b00, i_q[1:0]}
                           : {i_q[1:0] ^ upl, i_q[1:0]};
    wire [7:0] wa_l = trig ? 8'd0 : wp_l;
    wire       we_l = trig | (busy_l & (acc_l_n >= {1'b0, win_l}));
    wire [8:0] wd_l = trig ? {4'b0000, z_sticky | z_rise, i_q[5:2]}
                           : {i_q[5:2] ^ lol, z_sticky | z_rise, i_q[5:2]};

    integer k;
    initial begin
        for (k = 0; k < NDEP; k = k + 1) begin
            up_mem[k] = 4'b0000;
            lo_mem[k] = 9'b000000000;
        end
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cd     <= 25'd0;
            cd_done <= 1'b1;                       // 首次上电立刻允许一次采集
            busy_u <= 1'b0; busy_l <= 1'b0;
            wp_u   <= 8'd0;  wp_l  <= 8'd0;
            acc_u  <= 19'd0; acc_l <= 22'd0;
            win_u  <= 18'd256; win_l <= 22'd256;
            z_sticky <= 1'b0;
            upl    <= 2'd0;  lol <= 4'd0;
            armed  <= 1'b0;
            frames <= 16'd0;
            tmo    <= 22'd0;
            tmo_last <= 1'b0;
        end else begin
            // ---- 冷却（500 ms）----
            if (trig) begin
                cd <= 25'd0; cd_done <= 1'b0;
            end else if (!cd_done) begin
                if (cd == CD_MAX) cd_done <= 1'b1;
                else              cd <= cd + 25'd1;
            end

            // ---- 兜底看门狗：有 u 下降沿就清零，等不到就数到 200 ms（饱和）----
            //   ★ 清零条件必须跟着触发源走（v83：e_wrap → u_fall），否则 U 相
            //     不翻（uwven=0 / 不转）时看门狗永远清不掉，一帧都触发不了。
            if (u_fall)        tmo <= 22'd0;
            else if (!tmo_hit) tmo <= tmo + 22'd1;
            if (trig)          tmo_last <= trig_t;    // 本帧用了哪种触发

            // ---- 上区窗口：第 0 点在触发拍，之后 acc 越过 win_u 就采一点 ----
            if (we_u) begin
                upl          <= i_q[1:0];
                if (trig) begin
                    busy_u <= 1'b1;
                    wp_u   <= 8'd1;
                    acc_u  <= 19'd0;
                    //   4 × A 周期；A 缺席（aclk 已饱和到 0xFFFF）时兜底 1024 clk
                    //   = 20 µs，否则这一帧要拖 5.24 ms 才结束
                    win_u  <= a_absent ? 18'd1024 : {aclk, 2'b00};
                end else begin
                    acc_u <= acc_u_n - {1'b0, win_u};
                    if (wp_u == NDEP - 1) busy_u <= 1'b0;
                    else                  wp_u   <= wp_u + 8'd1;
                end
            end else if (busy_u) begin
                acc_u <= acc_u_n;
            end

            // ---- 下区窗口（顺带钉 Z 的窄脉冲：窗口内任何一次上升沿都记进
            //      当前样本的 zmark 位，写进 lo_mem 后清零）----
            if (we_l) begin
                lol          <= i_q[5:2];
                z_sticky     <= 1'b0;              // 已经写进这一点的 zmark
                if (trig) begin
                    busy_l <= 1'b1;
                    wp_l   <= 8'd1;
                    acc_l  <= 22'd0;
                    // ★ v84（主路径）：窗口 = **确定性** eclk*2048/pairs_eff = 一个电周期
                    //   （见 §1c）。完全不依赖 U 边沿，掉一拍 U 也不会把窗口打回 1024。
                    //   uper 只留作交叉校验（dbg_upok/dbg_scnt），不再定窗。
                    //   eclk 还是 0（一个传感器过零都没数到）时退回 1024 clk 并报
                    //   NO CAPTURE：窗口绝不为 0，否则 busy_l 永远不置位、一帧都采不到。
                    win_l  <= eclk_ok ? win_det : 22'd1024;
                end else begin
                    acc_l <= acc_l_n - {1'b0, win_l};
                    if (wp_l == NDEP - 1) busy_l <= 1'b0;
                    else                  wp_l   <= wp_l + 8'd1;
                end
            end else if (busy_l) begin
                acc_l     <= acc_l_n;
                z_sticky  <= z_sticky | z_rise;
            end

            // ---- 帧计数 / 冻结标志 ----
            if (trig) begin
                frames <= frames + 16'd1;
                armed  <= 1'b1;
            end
        end
    end

    // =========================================================================
    // 4b. 存储写口：**单独一个 always 块，且没有异步复位**
    //   ★ 这是 LUTRAM 能不能被推断出来的关键：Vivado 的规则是「写存储的进程里
    //     出现 negedge rst_n 就拒收」（日志原文：RAM is sensitive to asynchronous
    //     reset signal, this RTL style is not supported），即使写语句根本不在复位
    //     分支里也一样。所以写地址/写数据/写使能都做成组合线网（见 §4 的 wa_u/wd_u/
    //     we_u），写操作只在这里出现一次。
    //   分布式 RAM 上电全 0（initial 只是为了仿真时不留 X）。
    // =========================================================================
    always @(posedge clk) begin
        if (we_u) up_mem[wa_u] <= wd_u;
        if (we_l) lo_mem[wa_l] <= wd_l;
    end

    // =========================================================================
    // 5. 读口：dx -> 样本号 -> 异步读 -> 打一拍（与 cx=px2 两拍对齐）
    //    856 px / 256 点 = 3.344 px/点 ⇒ 样本号 = (dx * 1024/3.344) / 1024
    //    = (dx * 306) >> 10。306 = 256 + 32 + 16 + 2，综合后是移位加法，
    //    不需要乘法器（spec §7.2）。
    //    ★ 与 disp_engine 的相位契约：本模块 ru/rl 打 **1** 拍，engine 里
    //      lg_w/lg_ew 再打 1 拍，合计 2 拍 = cx 从 pix_x 的延迟 ⇒ 像素列
    //      cx 上看到的就是 cx 这一列的样本（v77 之前合计 4 拍，整条波形左移 2 px）。
    // =========================================================================
    wire [18:0] rp     = dx * 19'd306;   // dx 在框外会回绕到 936..1023，留 19 位不溢出
    wire [7:0]  sidx   = rp[17:10];

    //   Z 的竖标位置：z_pos 是 §1c 在采集期间直接记下的**样本号**（不再做角度减法）。
    //   z_pos 与 sidx 同宽，比较本身只有两个 8 位相等判断；z_pos-1 让竖标有
    //   2 个样本（6.7 px）宽，与水平轨的 2 px 粗线风格一致。
    wire        z_hit  = (sidx == z_pos) || (sidx == (z_pos - 8'd1));

    reg [3:0] ru;
    reg [8:0] rl;
    reg       z_r;

    always @(posedge clk) begin
        ru  <= up_mem[sidx];
        rl  <= lo_mem[sidx];
        z_r <= z_hit;
    end

    assign qu  = ru[1:0];
    assign qv  = ru[3:2];                   // 样本边界上的跳变 => 画竖线（写时算好）
    assign ql  = rl[3:0];
    assign qlv = rl[8:5];                   // 四个通道的跳变位
    //   竖标 = "窗口里真抓到 Z"（rl[4]，zmark 位）或 "Z 记下的样本号在这里"（z_r）；
    //   ★ z_ok 门控：一次都没标过就不画（z_pos 是初值 0，会凭空多一根竖线）。
    assign qz  = z_ok & (rl[4] | z_r);

    // =========================================================================
    // 6. 屏上自证抽头（v79）
    //    只读、只给 disp 侧的 p4_dbg_lab 用，不参与任何采样逻辑。放在文件末尾
    //    是因为 wp_l/wp_u 等寄存器在 §4 才声明。
    //    ECLK = 一个**角度抽头信号周期**的 clk 数（v83 更正：不是电周期！
    //           上板实测 0x52F = 1327 clk；2048 个/转 ⇒ 2.72 M clk = 54.4 ms/转
    //           ⇒ 1103 rpm，与串口 1095 rpm 对得上。电周期看下区波形本身）
    //    WP   = 下区写指针（跑起来才会变；停在 0 说明一帧都没写）
