//=============================================================================
// disp/wave_trace.v —— P2 输入波形页的轨迹采样器（v87：预触发环形缓冲）
//-----------------------------------------------------------------------------
//   把连续的两路 16 bit 有符号样本（校正后 sin / cos）变成一张**每列一条
//   竖直线段**的表，供 disp/disp_engine.v 的像素通路做一次区间比较。
//
//   ★ 为什么不存"每个采样点的行号"而存"线段的上下沿"：
//     spec 7.2 明令**禁止在像素通路里实时栅格化折线**。存单点行号的话，
//     两个相邻列的点之间要靠像素通路连线（斜率计算 + 循环），组合深度不可控；
//     存 [lo, hi] 之后，像素通路只剩 `lo <= ry <= hi` 两个比较器 —— 几何
//     全部在消隐期/帧内预栅格化完成。存储代价是每列 2 字节而不是 1 字节
//     （2048 x 32 bit 仍然只要 2 块 RAMB36）。
//
//   ★ v87（任务 A）：写指针**自由跑**、读地址**反旋转**。
//-----------------------------------------------------------------------
//   现场现象：触发点确实落在第 472 列，但**中线（列 472/473 交界）处波形有
//   一处断裂/错位**。根因不是触发，而是写序与读序不一致：
//     v86 写指针从 472 起、写满 943 后回绕 0 继续写，凑满 944 列换面。
//     显示器却按 0->943 线性读 ⇒ 左半边读到的其实是**触发之后**的晚段、
//     右半边是**早段**，时间顺序在列 0 被打断，屏上就是中线处的错位。
//
//   现在改成标准的"预触发环形缓冲 + 读侧反旋转"：
//     - 写侧：不再等触发，也不复位指针。每 sweep_div 拍写一个样本，
//       wcol 在 0..1023（整块 1024 深的 RAM）里自增回绕。
//     - 触发只"打点"：s_n 由负穿正时 armed<=1、post<=1（该样本即 t0）。
//       之后每写一个样本 post<=post+1。
//     - 抓满 472 个"触发后"样本（该样本 = t0+471，因为 t0 本身占 1 个）
//       时封帧：win_start <= (wcol + 81) & 0x3FF、disp_buf <= wr_buf、
//       wr_buf <= ~wr_buf、armed <= 0。写指针**不归零**，在新面里接着跑。
//     - 读侧：raddr = {disp_buf, (win_start + col) & 0x3FF}，col = 0..943。
//       于是列 i 显示 t0-472+i，列 472 正好是 t0，左右各 472 列，时间序
//       单调不减、中线处**没有跳变**。
//
//   为什么 win_start 是 wcol + 81 而不是 +1：
//     封帧那一拍写的是窗口最**新**样本 t0+471（地址 A）。窗口最老样本是
//     t0-472，它在环里的地址是 A-943 ≡ A+81 (mod 1024) —— 944 的窗口塞在
//     1024 的环里，空着 80 格。+1 是"整环 1024 窗口"的算法，会让第 472 列
//     落在 t0+944 而不是 t0（tb_wave_trace 会把这个错抓出来）。
//
//   ★ 为什么封帧后允许立刻换面（而不是等 frame_st）：
//     换面后"读的面"是刚封好的完整窗口，"写的面"是两轮之前的旧面 ——
//     读写始终落在不同 bank，不会撕。当前这一帧的上半部分仍是旧窗口，但两个
//     窗口都是**同一个触发相位**（都以过零点为 t0）的 944 列，画面形状一致，
//     所以接缝不可见；比起"等 frame_st 才换面"（那段时间新样本无处可写、
//     预触发历史被暂停）更符合"连续写"的语义。frame_st 因此不再参与换面，
//     只作为显示同步的参考输入保留（本模块不再使用它，见端口注释）。
//
//   ★ 连续写 + "预填 472"门控：
//     换面那一刻新写面的内容还是**两轮之前**的旧窗口，必须再写满 472 个新
//     样本，环里 t0 之前的那 472 格才都是本轮的新数据（否则预触发半屏会是
//     上一轮/复位初值）。因此 armed 只在 fresh>=472 后才允许拉高；未就绪时
//     到达的过零点直接丢弃（trig_pend<=0），保证触发相位仍然锁在真实过零点。
//
//   ★ 扫描与帧的同步（老注释，保留背景）：
//     SWEEP_DIV=128 时 944 列只需 120,832 个拍，而一帧 853,440 拍 ⇒ 每轮都能
//     在帧内跑完并留出余量。
//
//   ★ v17/v77 的 de 门控历史：样本寄存器每拍都采（消隐期也是新样本），所以
//     时基必须连续 —— 本模块的 div 不分 de/消隐，每拍推进。
//
//   标度：16 bit 有符号样本 ±32768 映射成居中 ±128 行（`>>> 8`），再钳到
//     0..199。满量程只占 200 行里的 128 行（64%），超范围时钳位是**可见且
//     诚实**的（波形削顶），不会伪装成小信号。
//=============================================================================
`default_nettype none

module wave_trace #(
    parameter [10:0] SWEEP_LEN = 11'd944    // 一屏多少列（= 可画宽度）
)(
    input  wire               clk,
    input  wire               rst_n,
    input  wire               frame_st,     // v87 起不再使用（换面由封帧驱动）；保留端口兼容
    input  wire               de,           // v77 起不再使用（时基连续推进，见头注释）
    input  wire signed [15:0] s_n,          // 校正后 sin（A 通道）
    input  wire signed [15:0] c_n,          // 校正后 cos（B 通道）
    // 时基三档。0 = 2.4 ms（每列 128 拍）、1 = 300 µs（16 拍）、2 = 38 µs（2 拍）。
    // 分频比是**运行期**信号（AUTO 档会自己换档），不是编译期参数。
    input  wire [1:0]         gear,

    output reg                we,
    output reg  [10:0]        waddr,
    output reg  [31:0]        wdata,
    output reg  [10:0]        wr_ptr,       // 调试：当前写列号（0..1023）
    output reg                wr_buf,       // 正在写的那一面
    output reg                disp_buf,     // 正在显示的那一面（封帧时取自 wr_buf）
    // v87：窗口起点（环内地址）。读侧必须用 (win_start + col) & 0x3FF 反旋转。
    output reg  [9:0]         win_start,
    // v87：封帧单拍脉冲（TB 与调试用；板上不接）
    output reg                cap_stb
);

    // ---- 样本 -> 通道内相对行（0 = 顶端，199 = 底端，99 = 中线）----
    wire signed [15:0] ra = 16'sd99 - (s_n >>> 8);
    wire signed [15:0] rb = 16'sd99 - (c_n >>> 8);

    wire [7:0] ya = (ra < 16'sd0)   ? 8'd0   :
                    (ra > 16'sd199) ? 8'd199 : ra[7:0];
    wire [7:0] yb = (rb < 16'sd0)   ? 8'd0   :
                    (rb > 16'sd199) ? 8'd199 : rb[7:0];

    // ---- 与上一列连成线段：取两列行的 min/max ----
    reg [7:0] ya_p, yb_p;

    wire [7:0] a_lo = (ya < ya_p) ? ya    : ya_p;
    wire [7:0] a_hi = (ya < ya_p) ? ya_p  : ya;
    wire [7:0] b_lo = (yb < yb_p) ? yb    : yb_p;
    wire [7:0] b_hi = (yb < yb_p) ? yb_p  : yb;

    wire [31:0] word = {a_hi, a_lo, b_hi, b_lo};

    reg [7:0] div;
    // 一列占多少个拍。128 需要 8 bit，故 div 从 12 bit 收到 8 bit。
    wire [7:0] sweep_div = (gear == 2'd0) ? 8'd128 :
                           (gear == 2'd1) ? 8'd16  : 8'd2;

    //=========================================================================
    // 预触发环形缓冲
    //=========================================================================
    // 944 的窗口放进 1024 的环里，空 80 格；封帧时窗口最老样本 = 写地址 + 81。
    localparam [9:0] WIN_LEAD = 10'd81;    // 1024 - 944 + 1

    reg        s_neg_q;    // 上一拍 sin 是否为负（过零检测）
    reg        trig_pend;  // 已过零、等下一次"写拍"落点
    reg        armed;      // 本窗口已锁定 t0，正在等 t0+471
    reg [9:0]  post;       // 自 t0 起已写入本窗口的样本数（t0 之后 = 1）
    reg [9:0]  fresh;      // 换面后已写入新面的样本数（饱和 472）
    reg [9:0]  wcol;       // 本拍要写的环内地址（0..1023 自增回绕）

    // 写拍：每 sweep_div 拍一次。用 >= 而不是 == —— 档位运行期可切，
    // 切换那一拍 div 可能已越过新档位上限，用 == 会永远对不上（老 bug）。
    wire wr_tick = (div >= sweep_div - 8'd1);
    wire s_rise  = (s_n >= 16'sd0) && s_neg_q;
    wire ready   = (fresh == 10'd472);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            div       <= 8'd0;
            we        <= 1'b0;
            waddr     <= 11'd0;
            wdata     <= 32'd0;
            wr_ptr    <= 11'd0;
            wr_buf    <= 1'b0;
            disp_buf  <= 1'b0;
            win_start <= 10'd0;
            cap_stb   <= 1'b0;
            ya_p      <= 8'd99;
            yb_p      <= 8'd99;
            wcol      <= 10'd0;
            s_neg_q   <= 1'b0;
            trig_pend <= 1'b0;
            armed     <= 1'b0;
            post      <= 10'd0;
            fresh     <= 10'd0;
        end else begin
            we      <= 1'b0;
            cap_stb <= 1'b0;
            s_neg_q <= (s_n < 16'sd0);
            if (s_rise) trig_pend <= 1'b1;

            if (wr_tick) begin
                div <= 8'd0;

                // 连续写：每次写拍都落一个样本，与触发无关。
                we     <= 1'b1;
                waddr  <= {wr_buf, wcol};
                wdata  <= word;
                wr_ptr <= wcol;
                wcol   <= wcol + 10'd1;      // 10 bit ⇒ 1024 自动回绕
                ya_p   <= ya;
                yb_p   <= yb;

                if (!armed) begin
                    if (!ready) begin
                        // 预触发历史还没填满：丢弃过零点（相位仍锁真实过零）。
                        if (fresh != 10'd472) fresh <= fresh + 10'd1;
                        trig_pend <= 1'b0;
                    end else if (trig_pend) begin
                        // 本拍写入的就是 t0（窗口正中那一列）。
                        trig_pend <= 1'b0;
                        armed     <= 1'b1;
                        post      <= 10'd1;
                    end
                end else begin
                    if (post == 10'd471) begin
                        // 本拍写入的是 t0+471 ⇒ 窗口 [t0-472, t0+471] 齐了。
                        // 最老样本地址 = 写地址 A - 943 ≡ A + 81 (mod 1024)。
                        win_start <= wcol + WIN_LEAD;
                        disp_buf  <= wr_buf;
                        wr_buf    <= ~wr_buf;
                        armed     <= 1'b0;
                        post      <= 10'd0;
                        fresh     <= 10'd0;
                        cap_stb   <= 1'b1;
                    end else begin
                        post <= post + 10'd1;
                    end
                end
            end else begin
                div <= div + 8'd1;
            end
        end
    end

endmodule

`default_nettype wire
