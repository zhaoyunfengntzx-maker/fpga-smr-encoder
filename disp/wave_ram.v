//=============================================================================
// disp/wave_ram.v —— P2 输入波形页的轨迹表（双缓冲）
//-----------------------------------------------------------------------------
//   2048 x 32 bit = 64 Kbit（两块 RAMB36 或四块 RAMB18）。
//   地址 11 位 = {缓冲区, 列号}：低 10 位是列号（页面上 944 列只用 0..943），
//   最高位是**双缓冲**选择位。tracer 写 A 面时显示器读 B 面，帧首互换。
//
//   为什么要双缓冲（不是过度设计）：
//     单缓冲时第 x 列的样本在 `x * SWEEP_DIV` 拍被改写，而显示器扫到该列
//     是 `y * 1024 + ...` 拍 —— 两者谁先谁后逐行变化，于是同一帧里左边的列
//     画的是上一轮扫描的数据、右边的列是这一轮的 ⇒ 波形被撕成两半。
//     一帧 853,440 拍、一次扫描只要 ~120,832 拍，"改写比扫描快"救不了它：
//     撕裂的根因是**读写没有隔离**，只有让读写落在不同缓冲面才能消掉。
//
//   每个字 32 bit = {A_hi, A_lo, B_hi, B_lo}，含义见 disp/wave_trace.v：
//   它不是"某个采样点的值"，而是**这一列的竖直线段**（上一列到本列的行的
//   最小/最大值）。像素通路因此只需要一次比较，不需要画线。
//
//   ★ `initial` 显式铺成"中线"（每字节 99）而不是 0：xsim 里未初始化的 BRAM
//     读出来是 X，X 会顺着比较器污染"这一像素该是什么颜色"的判定，让所有底色
//     断言都读到 X。铺 99 则"还没采到样本"这件事在屏上表现为**两条居中直线**，
//     是可见且诚实的初始状态；铺 0 会画成贴顶的直线，看起来像信号削顶。
//     上板时综合出的 BRAM 初值就是这段 initial，所以这是仿真与硬件的**行为对齐**，
//     不是为了让测试通过而加的特例（v15 在 disp/text_ram.v 上踩过同一个坑）。
//=============================================================================
`default_nettype none

module wave_ram (
    input  wire        clk,
    input  wire        we,
    input  wire [10:0] waddr,
    input  wire [31:0] wdata,
    input  wire [10:0] raddr,
    output reg  [31:0] rdata
);

    reg [31:0] mem [0:2047];
    integer i;

    initial begin
        for (i = 0; i < 2048; i = i + 1)
            mem[i] = 32'h6363_6363;     // 四个字节都是 99 = 通道内第 99 行（中线）
    end

    always @(posedge clk) begin
        if (we)
            mem[waddr] <= wdata;
        rdata <= mem[raddr];
    end

endmodule

`default_nettype wire
