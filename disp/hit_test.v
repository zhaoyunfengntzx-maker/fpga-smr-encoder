// -----------------------------------------------------------------------------
//  disp/hit_test.v —— 触摸命中判定（控件矩形表 + 接触边沿握手）
//
//  为什么需要这个模块：
//    在这之前触摸通路是**通的** —— 准星跟手、坐标可读、P8 能显示诊断数字 ——
//    但没有任何控件知道自己的矩形被碰了。于是屏上的一切交互只能靠板载按键
//    （短按翻页、长按提交改值），而 docs/13_display_ui_requirements.md 的约束
//    C3 写的是"触摸修好后就走纯触屏，不设计按键兜底"：按键不是设计的一部分，
//    它只是触摸还没接通时的临时入口。
//    本模块就是那条缺失的边：把"屏幕上的一个点"翻译成"哪个控件被按了"。
//
//  ---------------------------------------------------------------------------
//  接口契约（与 disp/touch_ctrl.v 的握手一致）
//  ---------------------------------------------------------------------------
//    touch_i2c_ctrl 每读到一组新坐标就把 tch_toggle 翻转一次（touch_ctrl.v 的
//    头注释第 5 条），并且 tch_num / tch_x0 / tch_y0 / tch_toggle 是在**同一个
//    时钟沿**一起更新的（touch_ctrl.v:381-391）。所以：
//      * 以 tch_toggle 的跳变作为"这是一个新样本"的唯一判据，
//        不去猜 tch_num / tch_x0 什么时候是新的；
//      * tch_num == 0 表示这一组样本里没有接触点。
//    ★ tch_toggle 与 tch_num/tch_x0 同域（都在 sys_clk 上），本模块**不需要**
//      任何跨时钟域处理；这里做边沿检测只是为了"每组样本只处理一次"。
//
//    接触事件 hit_stb 的语义：
//      一次"按下"只报一次，而且必须先看到一组无触点样本才能再次报。
//      于是：按住不放不会连发；把手指从别处**拖进**控件也不会触发
//      （拖进来的那一刻 armed 已经被起点那次接触消耗掉了）。
//      这是有意的 —— 翻页与屏上改值都是"一次点击 = 一次动作"，
//      连发会让一次误触产生一串事务（P6 改值是两阶段提交 + 回读，
//      连发的后果不是"多翻一页"而是多个写事务叠在一起）。
//
//  ---------------------------------------------------------------------------
//  ★ v22：接触生命周期（长按 / 拖拽 / 滑动需要）
//  ---------------------------------------------------------------------------
//    上面那套"一次按下只报一次"对点击是对的，但它把两样东西丢掉了：
//      * **按住期间的连续位置** —— 全屏只有一个 hit_x/hit_y，而且是按下那一刻的；
//      * **抬起事件** —— 面板要"按住不动就加速、松开就停"，没有抬起就无法收尾。
//    docs/13_display_ui_requirements.md 的 6.3/6.5 要求倍频面板支持
//    「长按加速 + 离散滑条（档位吸附）」，这两件事都需要上面两样。所以本模块
//    在**不改原有语义**的前提下再输出三个信号（原 hit_stb/hit_id/hit_x/hit_y 的
//    行为一位都没变，翻页与卡片点击仍走那条路）：
//      held    当前有接触点（电平，不是脉冲）
//      rel_stb 单拍：抬起（从"有接触"回到"无接触"那一拍）
//      cur_x/cur_y  按住期间最新一组合法坐标（跟着手指走）
//    ★ cur_x/cur_y 只在坐标合法（xy_ok）时更新：面板把它当"手指现在在哪"用，
//      垃圾坐标一旦混进来，滑条会瞬间跳到边界。
//    ★ held 与 rel_stb 都由 `tch_toggle` 的"新样本"边沿驱动，与 hit_stb 同一个
//      时基 —— I2C 的采样率（约 100 Hz）就是手势的时间分辨率，不需要额外定时器。
//
//  ---------------------------------------------------------------------------
//  矩形表（★ 与 disp/disp_engine.v 的版面是**两处共同契约**）
//  ---------------------------------------------------------------------------
//    导航栏   x ∈ [0, 80)                    y ∈ [24 + 144*i, 24 + 144*(i+1))
//             ★ v58：6 项×96 → 4 项×144（边界 24/168/312/456/600）
//    状态条   y ∈ [0, 24)（通栏）
//             ★ v19 起右端细分：[信号 ●] x ∈ [736, 800)（指示，不可点）
//                              [告警 ▲] x ∈ [800, 864)（指示，不可点）
//                              v58：[系统 ⚙] 随 P8 删除，x ∈ [864, 928) 不再可点
//             x ∈ (928, 1024) 仍是抽头/触摸两条活性灯（x > 904 的历史区域
//             里 32 px 与本表的 ⚙ 重叠，所以灯区从 904 挪到 960）
//    卡片     3 列 x 2 行：
//             x ∈ {32, 352, 672} + [0, 288)
//             y ∈ {64, 336} + [0, 256)
//    P6 危险区按钮（清除锁存故障）**不在本表**：
//             x ∈ [184, 648)   y ∈ [512, 592) —— 与 P1 的两张 row1 卡片
//             （col0 x 96..384、col1 x 416..704，row1 y 336..592）大面积重叠，
//             而本模块不认识页号 ⇒ 放这里只有卡片之间那 32 px 的缝能点中。
//             改由策略层按坐标 + page==5 判（见 disp/enc_top_disp.v 4.9 节）。
//
//    ★ 为什么在这里又抄了一遍这些数字：
//      disp_engine.v 里那套常量作用在**像素坐标** (cx, cy) 上，这里作用在
//      **触摸坐标** (tch_x0, tch_y0) 上 —— 两者不是同一个信号，Verilog-2001
//      又没有共享常量包，所以只能各写一份。改版面的代价因此是"改两个文件"，
//      这一点由 disp/tb_hit_test.v 断言边界值（24/120/216/312/408/504、
//      x=80、卡片原点 96/416/736 与宽高 288/256）兜底：
//      只改一边会让测试台直接报出来，而不是上板点不中才发现。
//
//    ★ 卡片原点 96 = 导航栏 80 + 16 px 内边距：卡片列 0 的 x 从 96 起，
//      **不再压住导航列 [0,80)**。于是 P1 上导航的整个 80 px 都是有效触控宽度
//      （旧版卡片原点 32 时，x ∈ [32,80) 会被 in_card 抢走，导航只剩 32 px 可点）。
//      disp_engine.v 的 bg_sel 仍把 in_card 排在 in_nav 之前，这条优先级没变，
//      只是现在两个矩形不再相交。
//
//  ---------------------------------------------------------------------------
//  资源与路径
//  ---------------------------------------------------------------------------
//    全部是常数比较；输入是已寄存的触摸快照，输出再寄一拍。
//    组合深度 3 级 LUT（矩形比较 + 优先级 + 编号译码），
//    **完全不在像素路径上** —— 像素域只看得见 hit_stb / hit_id 的寄存输出。
// -----------------------------------------------------------------------------
`timescale 1ns / 1ps

module hit_test #(
    // 版面参数：与 disp/disp_engine.v 第 1 节的常量一一对应
    parameter [11:0] NAV_W   = 12'd80,
    parameter [11:0] NAV_Y0  = 12'd24,
    parameter [11:0] NAV_H   = 12'd144,
    // ★ v59：2 列 x 3 行（与 disp/disp_engine.v 的 CARD_* 同一契约）
    parameter [11:0] CARD_X0 = 12'd96,
    parameter [11:0] CARD_X1 = 12'd576,
    parameter [11:0] CARD_Y0 = 12'd64,
    parameter [11:0] CARD_Y1 = 12'd256,
    parameter [11:0] CARD_Y2 = 12'd448,
    parameter [11:0] CARD_W  = 12'd448,
    parameter [11:0] CARD_H  = 12'd152,
    // v58：状态条右端 ⚙（SBAR_SYS_*）随 P8 删除，参数一并撤掉。
    // v20：标题带"主操作按钮"（P1「标定」；v58 起 P4「展开」随 P5 删除）
    //   绘制 160x32（y 28..60）、命中放大到 40 px 高（y 24..64）。
    //   ★ 与 disp/disp_engine.v 的 TBTN_* 是两处共同契约（改一边必须改另一边）。
    parameter [11:0] TBTN_X0 = 12'd660,
    parameter [11:0] TBTN_X1 = 12'd820,
    parameter [11:0] TBTN_Y0 = 12'd24,
    parameter [11:0] TBTN_Y1 = 12'd64,
    // v60（T8）：P6 危险带右半侧的「演示」开关
    parameter [11:0] DEMO_X0 = 12'd840,
    parameter [11:0] DEMO_X1 = 12'd1000,
    parameter [11:0] DEMO_Y0 = 12'd24,
    parameter [11:0] DEMO_Y1 = 12'd64
)(
    input  wire        clk,
    input  wire        rst_n,

    // ---- 触摸快照（disp/enc_top_disp.v 里 touch_i2c_ctrl 的输出）----
    input  wire [2:0]  tch_num,      // 0 = 这一组样本没有接触点
    input  wire [15:0] tch_x0,       // 屏坐标，标称 0..1023
    input  wire [15:0] tch_y0,       // 屏坐标，标称 0..599
    input  wire        tch_toggle,   // 每得到一组新坐标翻转一次

    // ---- 命中结果 ----
    output reg         hit_stb,      // 单拍：发生了一次"按下"（无论有没有打中控件）
    output reg  [4:0]  hit_id,       // 打中的控件编号（HIT_NONE = 没打中任何控件）
    output reg  [11:0] hit_x,        // 触发这次判定的坐标（调试 / 测试台用）
    output reg  [11:0] hit_y,

    // ---- v22 接触生命周期（长按 / 拖拽 / 滑动用，见文件头）----
    output reg         held,         // 电平：当前有接触点
    output reg         rel_stb,      // 单拍：抬起
    output reg  [11:0] cur_x,        // 按住期间最新一组合法坐标
    output reg  [11:0] cur_y
);

    // =========================================================================
    // 1. 控件编号表
    //      0..3   导航项：0 总览 1 波形 2 时序 3 设置（v58：4 项×144 px）
    //      6      状态条本体（通栏）
    //      7      （空）原 v19 的 [系统 ⚙]：v58 删 P8 时一并撤掉，编号不复用
    //      8..13  卡片 = 8 + 列号 + 3*行号：
    //             8=列0行0  9=列1行0  10=列2行0
    //            11=列0行1 12=列1行1  13=列2行1
    //      14     （空）★ v19 计划放 P6 危险区按钮，**最终不放在这里**：
    //             它的矩形（x 184..648, y 512..592）与 P1 的两张 row1 卡片
    //             完全重叠，而本模块不认识页号 ⇒ 无论排在 in_card 之前还是
    //             之后都是错的（之前会抢 P1 卡片，之后会被卡片抢走，
    //             实际只有卡片之间那 32 px 缝能点中）。改由策略层按坐标 +
    //             页号判（见 disp/enc_top_disp.v 的 4.9 节）。
    //      15     ★ v20 标题带"主操作按钮"（HIT_TITLE_BTN）：
    //             它落在标题带（y 24..64），与卡片（y≥64）、导航（x<80）、
    //             状态条（y<24）、⚙（x≥864）**都不相交** ⇒ 可以安心放进本表。
    //             按钮**在这页代表什么**是策略层的事：P1 ⇒ P7（标定）、
    //             P4 ⇒ P5（六状态明细），别的页什么都不做。
    //             P2/P3 的 Tab 栏**不在本表**：它的矩形压在 P1 卡片 8/9 上，
    //             与危险区按钮同一个陷阱，同样交给策略层按坐标 + 页号判。
    //      31     没打中任何控件
    //    ★ 编号只描述"碰的是哪块矩形"，不描述"该干什么" —— 翻页 / 进编辑面板 /
    //      什么都不做，是 disp/enc_top_disp.v 的策略，不是命中判定的职责。
    //      包括"这一页还有没有这个控件"：页号只在策略层出现一次。
    //    ★ [信号 ●] 与 [告警 ▲] **没有编号**：按 spec 4.1，状态条里只有 ⚙ 是
    //      入口；v58 删 P8 时 ⚙ 也撤了 ⇒ 状态条现在整条都是纯指示器。
    // =========================================================================
    localparam [4:0] HIT_SBAR   = 5'd6;
    //    ★ 7 号（原 [系统 ⚙] → P8）v58 起不再使用，编号留空不复用 ——
    //      这样旧日志/旧文档里"id 7"永远唯一，不会指到别的东西上。
    localparam [4:0] HIT_CARD_B = 5'd8;
    localparam [4:0] HIT_TITLE_BTN = 5'd15;
    localparam [4:0] HIT_DEMO   = 5'd14;   // v60（T8）：P6 演示开关（原 14 是已删的 XY Tab）
    localparam [4:0] HIT_NONE   = 5'd31;

    // =========================================================================
    // 2. 坐标合法性
    //    面板标称 1024x600。超出范围的坐标（没锁定型号时可能是垃圾值）
    //    一律按"没打中"处理。
    //    ★ 不能只取低 12 位再比较：那样 1024 会被折成 0，
    //      在状态条左端凭空造出一次命中。
    // =========================================================================
    wire [11:0] tx = tch_x0[11:0];
    wire [11:0] ty = tch_y0[11:0];
    wire xy_ok = (tch_x0 < 16'd1024) && (tch_y0 < 16'd600);

    // =========================================================================
    // 3. 导航项：144 px 一档（v58：6 项 96 px -> 4 项 144 px）
    //    与 disp/disp_engine.v 的 nav_idx 是同一套边界（见文件头的"两处共同
    //    契约"）。4 项仍用比较器而不是除法器：144 不是 2 的幂。
    //    导航序号 0..3，页号用 NAV_PAGE 映射（0/1/3/5）—— 删页后页号保留空洞，
    //    避免把整张页号表推倒重编号（见 docs/21 §3.2）。
    // =========================================================================
    wire in_nav = xy_ok && (tx < NAV_W) && (ty >= NAV_Y0);
    wire [2:0] nav_i =
        (ty < (NAV_Y0 + NAV_H))   ? 3'd0 :   // 24..167   总览 -> P1
        (ty < (NAV_Y0 + NAV_H*2)) ? 3'd1 :   // 168..311  波形 -> P2
        (ty < (NAV_Y0 + NAV_H*3)) ? 3'd2 :   // 312..455  时序 -> P4
                                    3'd3;    // 456..599  设置 -> P6

    // =========================================================================
    // 4. 卡片 3 列 x 2 行
    // =========================================================================
    wire col0 = (tx >= CARD_X0) && (tx < (CARD_X0 + CARD_W));
    wire col1 = (tx >= CARD_X1) && (tx < (CARD_X1 + CARD_W));
    wire row0 = (ty >= CARD_Y0) && (ty < (CARD_Y0 + CARD_H));
    wire row1 = (ty >= CARD_Y1) && (ty < (CARD_Y1 + CARD_H));
    wire row2 = (ty >= CARD_Y2) && (ty < (CARD_Y2 + CARD_H));
    wire in_card = xy_ok & (col0 | col1) & (row0 | row1 | row2);

    wire [1:0] card_col = col0 ? 2'd0 : 2'd1;
    wire [1:0] card_row = row0 ? 2'd0 : (row1 ? 2'd1 : 2'd2);
    // ★ v59：8 + col + 2*row（行优先）。契约不变的两个下钻入口：
    //   标定 = 卡 3（id 10，转速）、ABZ = 卡 6（id 13，ABZ/UVW）。
    wire [4:0] card_id = HIT_CARD_B + {3'd0, card_col}
                                    + {2'd0, card_row, 1'b0};

    // =========================================================================
    // 5. 优先级译码 —— 必须与 disp/disp_engine.v 的 bg_sel 绘制优先级一致
    //      卡片（bg_sel:535-536 排第一）> 导航栏（:538）> 状态条（:537 通栏）
    //    状态条只可能和卡片/导航在 y 上互斥，但顺序写全是为了让"眼睛看到的
    //    层次"和"命中的层次"永远是同一条链。
    //    ★ v58：⚙（HIT_SYS）随 P8 删除 —— 图形与命中区一起撤掉，状态条右端
    //      不再有"点得着、没反应"的死入口。
    //    ★ v20 标题带主操作按钮：与上面的矩形在 y 上互斥（标题带 24..64、
    //      卡片从 64 起、状态条 <24），排在卡片/导航之后只是为了
    //      "眼睛看到的层次 == 命中的层次"这条规矩不破。
    wire in_tbtn = xy_ok && (tx >= TBTN_X0) && (tx < TBTN_X1) &&
                   (ty >= TBTN_Y0) && (ty < TBTN_Y1);
    //   v60（T8）：演示开关只在 P6 上有效（其他页点不到）。
    //   它落在危险带（y 504..599）右半侧，与左半的清除/恢复按钮互斥。
    wire in_demo = xy_ok && (tx >= DEMO_X0) && (tx < DEMO_X1) &&
                   (ty >= DEMO_Y0) && (ty < DEMO_Y1);

    wire [4:0] id_now = in_card ? card_id :
                        in_nav  ? {2'd0, nav_i} :
                        in_tbtn ? HIT_TITLE_BTN :
                        in_demo ? HIT_DEMO :
                        (xy_ok && (ty < NAV_Y0)) ? HIT_SBAR :
                        HIT_NONE;

    // =========================================================================
    // 6. 新样本检测 + 一次接触只报一次
    // =========================================================================
    reg  tch_tg_d = 1'b0;
    reg  armed    = 1'b1;          // 复位后允许第一次按下

    wire new_sample = (tch_toggle != tch_tg_d);
    wire has_point  = (tch_num != 3'd0);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            tch_tg_d <= 1'b0;
            armed    <= 1'b1;
            hit_stb  <= 1'b0;
            hit_id   <= HIT_NONE;
            hit_x    <= 12'd0;
            hit_y    <= 12'd0;
            held     <= 1'b0;
            rel_stb  <= 1'b0;
            cur_x    <= 12'd0;
            cur_y    <= 12'd0;
        end else begin
            tch_tg_d <= tch_toggle;
            hit_stb  <= 1'b0;              // 默认：单拍脉冲
            rel_stb  <= 1'b0;              // v22：默认：不是抬起那一拍
            if (new_sample) begin
                if (!has_point) begin
                    armed <= 1'b1;         // 抬起：重新武装
                    // v22 生命周期：这一拍是"抬起"（只有真的按着过才报）
                    if (held) rel_stb <= 1'b1;
                    held  <= 1'b0;
                end else begin
                    held <= 1'b1;          // v22：按住期间保持 1
                    // v22：记住手指现在在哪。★ 只在坐标合法时更新 —— 面板按
                    // 这个值做"档位吸附"，垃圾坐标混进来会让滑条跳到边界。
                    if (xy_ok) begin
                        cur_x <= tx;
                        cur_y <= ty;
                    end
                    if (armed) begin
                        armed   <= 1'b0;       // 一次接触只认一次，直到抬起
                        hit_stb <= 1'b1;
                        hit_id  <= id_now;
                        hit_x   <= tx;
                        hit_y   <= ty;
                    end
                end
            end
        end
    end

endmodule
