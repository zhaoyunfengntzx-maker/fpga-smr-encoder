//=============================================================================
// angle_lut.v —— 全周角度误差补偿表（S5）
//-----------------------------------------------------------------------------
// 解决什么
//   编码器刻度误差、安装偏心（1 次谐波）、码盘跳动等都是"机械角的确定性函数"。
//   单点/四点标定只能消掉 0 次和 1 次项的一部分，剩下的全周形状必须用表。
//   本模块是 4096×16 的查表 ROM：索引 = 机械角高 12 位（0.0879°/点 ≈ 5.3′），
//   输出 = 该角度处的角度修正量（16 位有符号，LSB 与 2^FRAC 细分一致）。
//
// 谁来填表
//   需要外部基准（激光干涉仪/自准直仪/双读数头）测一遍全周误差，主机把
//   err[i] 换算成 LSB 后写进表。没有基准时 `cfg_lut_en=0`，本模块完全旁路
//   （输出恒 0），不影响任何既有功能 —— 这是"先上板、后有基准再启用"的关键。
//
// 为什么是 4096 点而不是 32768 点
//   全周误差的主要成分是 1~2 次谐波（偏心/椭圆度），形状极平滑。4096 点已把
//   一个正弦周期分成 4096 段，量化残差 = A·(π/4096)²/2 ≈ A·2.9e-7，即使
//   A=50″ 也只有 1.5e-5″，完全可以忽略。再大只会白烧 BRAM。
//
// 时序
//   读：1 拍 BRAM 输出（读优先，与写冲突时读出旧值）。
//   由于修正量随角度是缓变的，1 拍（80 ns）的索引滞后最多造成 1/16 个索引
//   步长的错位，折算误差 <0.05 LSB，可以忽略 —— 不需要为它拉长流水线。
//
// 资源：4096×16 = 64 Kb ⇒ 2 个 RAMB36（读口 + 写口各一套）。
// 复位：同步、低有效。无 initial / #delay / inout / SystemVerilog 语法。
// 综合：数组不上电初始化，上电后内容未定义 ⇒ 主机必须先写表或保持 en=0。
//=============================================================================
module angle_lut (
    input  wire        clk,
    input  wire        rst_n,

    // 读口（每拍给索引，下一拍出数据）
    input  wire [11:0] rd_idx,
    output reg  [15:0] rd_q,

    // 写口（主机通过寄存器写入，先写数据再拉高 wr_en）
    input  wire        wr_en,
    input  wire [11:0] wr_addr,
    input  wire [15:0] wr_data
);

    (* ram_style = "block" *)
    reg [15:0] mem [0:4095];

    always @(posedge clk) begin
        if (wr_en)
            mem[wr_addr] <= wr_data;
    end

    always @(posedge clk) begin
        if (!rst_n)
            rd_q <= 16'd0;
        else
            rd_q <= mem[rd_idx];
    end

endmodule
